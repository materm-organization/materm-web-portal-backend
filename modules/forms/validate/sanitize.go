// Package validate checks a form submission against the form definition (doc/08 section 6.2) with exactly the
// rules of the frontend's contact-validation.ts, so a message that the browser accepts is accepted here and
// the other way round. It has two halves:
//
//   - sanitize.go: sanitizeText of the frontend, character for character (NFC, line ends, control
//     characters, space collapsing, trim, cap), including the places where JavaScript differs from Go: a
//     string length is counted in UTF-16 code units, trim() removes U+FEFF, and \s is the Unicode white space
//     set.
//   - schema.go: a small validator driven by the form's json_schema, with the error codes of the frontend
//     (required, email, messageShort, phone) for the contact form and generic codes for any other form.
//
// The golden table testdata/parity.json is generated by running the real contact-validation.ts under node
// (see the test), not written by hand.
package validate

import (
	"strings"
	"unicode"
	"unicode/utf16"
	"unicode/utf8"

	"golang.org/x/text/unicode/norm"
)

// jsSpace reports whether r is white space or a line terminator in the sense of JavaScript's String.trim and
// of the regular expression class \s: TAB, VT, FF, SP, NBSP, ZWNBSP (U+FEFF), the Zs category, LF, CR, LS, PS.
// (unicode.IsSpace differs: it includes U+0085 and leaves out U+FEFF.)
func jsSpace(r rune) bool {
	switch r {
	case '\t', '\n', '\v', '\f', '\r', ' ', 0x00a0, 0x1680, 0x2028, 0x2029, 0x202f, 0x205f, 0x3000, 0xfeff:
		return true
	}
	return r >= 0x2000 && r <= 0x200a
}

// UTF16Len is JavaScript's String.length of s: the number of UTF-16 code units.
func UTF16Len(s string) int {
	n := 0
	for _, r := range s {
		if r >= 0x10000 {
			n += 2
		} else {
			n++
		}
	}
	return n
}

// sliceUnits is s.slice(0, max) counted in UTF-16 code units. A surrogate pair that would be cut in the
// middle is dropped whole (JavaScript would keep a lone surrogate, which cannot be stored as text).
func sliceUnits(s string, max int) string {
	if max <= 0 {
		return ""
	}
	n := 0
	for i, r := range s {
		w := 1
		if r >= 0x10000 {
			w = 2
		}
		if n+w > max {
			return s[:i]
		}
		n += w
	}
	return s
}

// SanitizeText is sanitizeText(value, max, {multiline}) of contact-validation.ts: a non-string is "", then
// NFC, CRLF and lone CR become LF, control characters (Unicode Cc) are removed - or, in a single-line field,
// replaced by a space with runs of two or more spaces collapsed to one - then trim and a cut at max UTF-16
// code units (the cut comes after the trim and is not trimmed again, as in the frontend).
func SanitizeText(value any, max int, multiline bool) string {
	s, ok := value.(string)
	if !ok {
		return ""
	}
	if !utf8.ValidString(s) {
		s = strings.ToValidUTF8(s, "�")
	}
	s = norm.NFC.String(s)
	s = strings.ReplaceAll(s, "\r\n", "\n")
	s = strings.ReplaceAll(s, "\r", "\n")

	var b strings.Builder
	b.Grow(len(s))
	if multiline {
		for _, r := range s {
			if unicode.Is(unicode.Cc, r) && r != '\n' && r != '\t' {
				continue
			}
			b.WriteRune(r)
		}
	} else {
		prevSpace := false
		for _, r := range s {
			if unicode.Is(unicode.Cc, r) {
				r = ' '
			}
			if r == ' ' {
				if prevSpace {
					continue
				}
				prevSpace = true
			} else {
				prevSpace = false
			}
			b.WriteRune(r)
		}
	}
	return sliceUnits(strings.TrimFunc(b.String(), jsSpace), max)
}

// ValidEmail is EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]{2,}$/ of the frontend, evaluated by hand because RE2's \s
// is ASCII only and the {2,} counts UTF-16 code units: exactly one "@", no white space anywhere, something
// before the "@", and after it a "." with at least one character before and at least two after it.
func ValidEmail(s string) bool {
	at := strings.IndexByte(s, '@')
	if at <= 0 || strings.IndexByte(s[at+1:], '@') >= 0 {
		return false
	}
	if strings.IndexFunc(s, jsSpace) >= 0 {
		return false
	}
	units := utf16.Encode([]rune(s[at+1:]))
	for i := 1; i+3 <= len(units); i++ {
		if units[i] == '.' {
			return true
		}
	}
	return false
}
